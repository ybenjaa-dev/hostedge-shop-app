// Bundles /migrations/*.sql into a TS module: Workers have no filesystem, so ensureSchema embeds them.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const files = readdirSync("migrations").filter((f) => f.endsWith(".sql")).sort();
const list = files.map((f) => ({
  name: f.replace(/\.sql$/, ""),
  statements: readFileSync(`migrations/${f}`, "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
}));
writeFileSync(
  "src/db/migrations.generated.ts",
  `// AUTO-GENERATED by scripts/gen-migrations.mjs — do not edit.\nexport const MIGRATIONS: { name: string; statements: string[] }[] = ${JSON.stringify(list, null, 2)};\n`,
);
console.log(`bundled ${files.length} migration(s)`);
